//! File-drop transports for partner delivery (F6).
//!
//! Most DSPs take DDEX deliveries as a file drop: SFTP (the industry
//! default), or an S3-compatible bucket. The adapters (`crate::partners`)
//! only see [`FileTransport`]; which wire is used comes from the partner's
//! config file.
//!
//! Visibility rule: a file appears at its final name only once it is
//! complete (SFTP uploads to `name.part` and renames; S3 PUT is atomic), so
//! a partner scanning the drop never ingests half a file.
//!
//! Errors are classified for the no-duplicate-send rule: `Unreachable`
//! means the connection failed before anything was written; `Failed` means
//! the transfer may have partially happened. The DDEX adapter turns both
//! into a safe retry as long as the completion marker was never written.
use crate::error::{Error, Result};
use crate::partner_config::{Secret, TransportConfig};
use async_trait::async_trait;
use hmac::{Hmac, KeyInit, Mac};
use sha2::{Digest, Sha256};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::time::Duration;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TransportError {
    /// Nothing reached the partner (DNS, connect, auth, host key).
    Unreachable(String),
    /// The operation failed after the session was established.
    Failed(String),
    NotFound,
}

impl std::fmt::Display for TransportError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Unreachable(d) => write!(f, "unreachable: {d}"),
            Self::Failed(d) => write!(f, "failed: {d}"),
            Self::NotFound => f.write_str("not found"),
        }
    }
}

pub type TResult<T> = std::result::Result<T, TransportError>;

/// One upload in a batch: local source (or inline bytes) and remote path
/// relative to the transport root.
#[derive(Debug, Clone)]
pub enum Upload {
    File { local: PathBuf, remote: String },
    Bytes { bytes: Vec<u8>, remote: String },
}

impl Upload {
    pub fn remote(&self) -> &str {
        match self {
            Self::File { remote, .. } | Self::Bytes { remote, .. } => remote,
        }
    }
}

#[async_trait]
pub trait FileTransport: Send + Sync {
    /// Upload every file, creating directories as needed. Files become
    /// visible at their final names only when complete.
    async fn put_all(&self, uploads: &[Upload]) -> TResult<()>;
    /// File names (not paths) directly inside `dir`. A missing dir is empty.
    async fn list(&self, dir: &str) -> TResult<Vec<String>>;
    /// Read one (small) file: ACKs, result files.
    async fn get(&self, path: &str, max_bytes: u64) -> TResult<Vec<u8>>;
    /// Connection + authentication + root listing check.
    async fn probe(&self) -> TResult<()>;
    fn describe(&self) -> String;
}

/// Remote paths are generated by us (UPC, timestamps, codes); anything else
/// is refused rather than quoted.
pub fn valid_remote_path(p: &str) -> bool {
    !p.is_empty()
        && p.len() <= 512
        && p.bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"._-/".contains(&b))
        && !p.split('/').any(|s| s == ".." || s == ".")
        && !p.contains("//")
}

pub fn join(root: &str, rel: &str) -> String {
    let root = root.trim_end_matches('/');
    let rel = rel.trim_start_matches('/');
    if root.is_empty() {
        format!("/{rel}")
    } else {
        format!("{root}/{rel}")
    }
}

fn parent_dirs(path: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let parts: Vec<&str> = path.split('/').collect();
    for (i, part) in parts.iter().enumerate() {
        if i + 1 == parts.len() {
            break;
        }
        if part.is_empty() {
            if i == 0 {
                cur.push('/');
            }
            continue;
        }
        if !cur.is_empty() && !cur.ends_with('/') {
            cur.push('/');
        }
        cur.push_str(part);
        out.push(cur.clone());
    }
    out
}

pub fn build(config: &TransportConfig) -> Result<Option<std::sync::Arc<dyn FileTransport>>> {
    Ok(Some(match config {
        TransportConfig::Sftp {
            host,
            port,
            username,
            private_key,
            known_hosts,
            remote_root,
            connect_timeout_secs,
            transfer_timeout_secs,
        } => std::sync::Arc::new(SftpTransport {
            host: host.clone(),
            port: *port,
            username: username.clone(),
            key: private_key.resolve_path("id_partner")?,
            known_hosts: known_hosts.resolve_path("known_hosts")?,
            root: remote_root.clone(),
            connect_timeout: Duration::from_secs((*connect_timeout_secs).clamp(3, 120)),
            transfer_timeout: Duration::from_secs((*transfer_timeout_secs).clamp(30, 6 * 3600)),
        }),
        TransportConfig::S3 {
            endpoint,
            region,
            bucket,
            prefix,
            access_key_id,
            secret_access_key,
        } => std::sync::Arc::new(S3Transport::new(
            endpoint,
            region,
            bucket,
            prefix,
            access_key_id.resolve()?,
            secret_access_key.resolve()?,
        )?),
        TransportConfig::Local { root } => std::sync::Arc::new(LocalTransport::new(root.clone())),
        TransportConfig::None => return Ok(None),
    }))
}

