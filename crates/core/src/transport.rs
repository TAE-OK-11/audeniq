/// Local directory drop (staging rehearsals, tests, or a partner mount).
pub struct LocalTransport {
    root: PathBuf,
}

impl LocalTransport {
    pub fn new(root: PathBuf) -> Self {
        Self { root }
    }
    fn path(&self, rel: &str) -> TResult<PathBuf> {
        let rel = rel.trim_start_matches('/');
        if !rel.is_empty() && !valid_remote_path(rel) {
            return Err(TransportError::Failed(format!("invalid path {rel}")));
        }
        Ok(self.root.join(rel))
    }
}

#[async_trait]
impl FileTransport for LocalTransport {
    async fn put_all(&self, uploads: &[Upload]) -> TResult<()> {
        if !self.root.is_dir() {
            return Err(TransportError::Unreachable("root missing".into()));
        }
        for u in uploads {
            let dest = self.path(u.remote())?;
            if let Some(parent) = dest.parent() {
                tokio::fs::create_dir_all(parent)
                    .await
                    .map_err(|e| TransportError::Failed(e.to_string()))?;
            }
            let part = dest.with_extension(format!(
                "{}part",
                dest.extension()
                    .map(|e| format!("{}.", e.to_string_lossy()))
                    .unwrap_or_default()
            ));
            match u {
                Upload::File { local, .. } => tokio::fs::copy(local, &part).await.map(|_| ()),
                Upload::Bytes { bytes, .. } => tokio::fs::write(&part, bytes).await,
            }
            .map_err(|e| TransportError::Failed(e.to_string()))?;
            tokio::fs::rename(&part, &dest)
                .await
                .map_err(|e| TransportError::Failed(e.to_string()))?;
        }
        Ok(())
    }
    async fn list(&self, dir: &str) -> TResult<Vec<String>> {
        let p = self.path(dir)?;
        let mut out = Vec::new();
        let mut rd = match tokio::fs::read_dir(&p).await {
            Ok(rd) => rd,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(out),
            Err(e) => return Err(TransportError::Failed(e.to_string())),
        };
        while let Some(e) = rd
            .next_entry()
            .await
            .map_err(|e| TransportError::Failed(e.to_string()))?
        {
            out.push(e.file_name().to_string_lossy().to_string());
        }
        out.sort();
        Ok(out)
    }
    async fn get(&self, path: &str, max_bytes: u64) -> TResult<Vec<u8>> {
        let p = self.path(path)?;
        match tokio::fs::metadata(&p).await {
            Ok(m) if m.len() > max_bytes => {
                return Err(TransportError::Failed("file too large".into()));
            }
            Ok(_) => {}
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
                return Err(TransportError::NotFound);
            }
            Err(e) => return Err(TransportError::Failed(e.to_string())),
        }
        tokio::fs::read(&p)
            .await
            .map_err(|e| TransportError::Failed(e.to_string()))
    }
    async fn probe(&self) -> TResult<()> {
        if self.root.is_dir() {
            Ok(())
        } else {
            Err(TransportError::Unreachable("root missing".into()))
        }
    }
    fn describe(&self) -> String {
        format!("file://{}", self.root.display())
    }
}

