/// SFTP through the system OpenSSH client (`sftp -b -`): key auth only,
/// strict host-key checking against the pinned known_hosts, no agent, no
/// password prompts. OpenSSH is the most widely interoperable SFTP client
/// DSP ingestion servers are tested against, and keeps the crypto stack out
/// of this binary. `SFTP_BIN` overrides the executable.
pub struct SftpTransport {
    pub host: String,
    pub port: u16,
    pub username: String,
    pub key: PathBuf,
    pub known_hosts: PathBuf,
    pub root: String,
    pub connect_timeout: Duration,
    pub transfer_timeout: Duration,
}

/// Quote a local path for an sftp batch line (paths we control: temp dirs).
fn sftp_quote(s: &str) -> TResult<String> {
    if s.contains('"') || s.contains('\n') || s.contains('\\') {
        return Err(TransportError::Failed("unquotable path".into()));
    }
    Ok(format!("\"{s}\""))
}

impl SftpTransport {
    async fn run(&self, script: &str, timeout: Duration) -> TResult<String> {
        use tokio::io::AsyncWriteExt;
        let bin = std::env::var("SFTP_BIN").unwrap_or_else(|_| "sftp".into());
        let mut cmd = tokio::process::Command::new(bin);
        cmd.arg("-b")
            .arg("-")
            .arg("-q")
            .arg("-P")
            .arg(self.port.to_string())
            .arg("-i")
            .arg(&self.key)
            .arg("-o")
            .arg("BatchMode=yes")
            .arg("-o")
            .arg("IdentitiesOnly=yes")
            .arg("-o")
            .arg("StrictHostKeyChecking=yes")
            .arg("-o")
            .arg(format!("UserKnownHostsFile={}", self.known_hosts.display()))
            .arg("-o")
            .arg("GlobalKnownHostsFile=/dev/null")
            .arg("-o")
            .arg(format!("ConnectTimeout={}", self.connect_timeout.as_secs()))
            .arg("-o")
            .arg("ServerAliveInterval=15")
            .arg("-o")
            .arg("ServerAliveCountMax=4")
            .arg(format!("{}@{}", self.username, self.host))
            .stdin(std::process::Stdio::piped())
            .stdout(std::process::Stdio::piped())
            .stderr(std::process::Stdio::piped())
            .kill_on_drop(true);
        let mut child = cmd
            .spawn()
            .map_err(|e| TransportError::Unreachable(format!("sftp not runnable: {e}")))?;
        if let Some(mut stdin) = child.stdin.take() {
            stdin
                .write_all(script.as_bytes())
                .await
                .map_err(|e| TransportError::Unreachable(e.to_string()))?;
        }
        let out = tokio::time::timeout(timeout, child.wait_with_output())
            .await
            .map_err(|_| TransportError::Failed("sftp timed out".into()))?
            .map_err(|e| TransportError::Failed(e.to_string()))?;
        let stdout = String::from_utf8_lossy(&out.stdout).to_string();
        if out.status.success() {
            return Ok(stdout);
        }
        let stderr: String = String::from_utf8_lossy(&out.stderr)
            .chars()
            .take(400)
            .collect();
        // ssh exits 255 when the connection itself failed (DNS, refused,
        // host key, auth): nothing was transferred. Any other failure
        // happened inside an established session.
        if out.status.code() == Some(255)
            || stderr.contains("Connection refused")
            || stderr.contains("Could not resolve")
            || stderr.contains("Permission denied")
            || stderr.contains("Host key verification failed")
            || stderr.contains("Connection closed")
                && !stdout.lines().any(|l| l.starts_with("sftp>"))
        {
            Err(TransportError::Unreachable(stderr))
        } else if stderr.contains("No such file") || stderr.contains("not found") {
            Err(TransportError::NotFound)
        } else {
            Err(TransportError::Failed(stderr))
        }
    }
}

#[async_trait]
impl FileTransport for SftpTransport {
    async fn put_all(&self, uploads: &[Upload]) -> TResult<()> {
        let tmp = tempdir()?;
        let mut script = String::new();
        let mut made = std::collections::BTreeSet::new();
        for (i, u) in uploads.iter().enumerate() {
            if !valid_remote_path(u.remote().trim_start_matches('/')) {
                return Err(TransportError::Failed(format!(
                    "invalid remote path {}",
                    u.remote()
                )));
            }
            let remote = join(&self.root, u.remote());
            for d in parent_dirs(&remote) {
                if made.insert(d.clone()) {
                    // '-' prefix: an existing directory is not an error.
                    script.push_str(&format!("-mkdir {d}\n"));
                }
            }
            let local = match u {
                Upload::File { local, .. } => local.clone(),
                Upload::Bytes { bytes, .. } => {
                    let p = tmp.join(format!("inline-{i}"));
                    tokio::fs::write(&p, bytes)
                        .await
                        .map_err(|e| TransportError::Failed(e.to_string()))?;
                    p
                }
            };
            let local = sftp_quote(&local.to_string_lossy())?;
            // Upload under .part, then rename: the partner never sees a
            // partial file at its final name. A stale final name from an
            // earlier failed attempt is removed first ('-': may not exist).
            script.push_str(&format!("put {local} {remote}.part\n"));
            script.push_str(&format!("-rm {remote}\n"));
            script.push_str(&format!("rename {remote}.part {remote}\n"));
        }
        let r = self.run(&script, self.transfer_timeout).await;
        let _ = tokio::fs::remove_dir_all(&tmp).await;
        r.map(|_| ())
    }
    async fn list(&self, dir: &str) -> TResult<Vec<String>> {
        let rel = dir.trim_start_matches('/');
        if !rel.is_empty() && !valid_remote_path(rel) {
            return Err(TransportError::Failed("invalid path".into()));
        }
        let path = if rel.is_empty() {
            self.root.clone()
        } else {
            join(&self.root, rel)
        };
        // '-ls': a missing directory is an empty listing, not an error.
        let out = self
            .run(&format!("-ls -1 {path}\n"), self.connect_timeout * 3)
            .await?;
        let mut names: Vec<String> = out
            .lines()
            .map(str::trim)
            .filter(|l| !l.is_empty() && !l.starts_with("sftp>") && !l.contains("not found"))
            .filter_map(|l| l.rsplit('/').next().map(str::to_string))
            .filter(|n| n != "." && n != "..")
            .collect();
        names.sort();
        names.dedup();
        Ok(names)
    }
    async fn get(&self, path: &str, max_bytes: u64) -> TResult<Vec<u8>> {
        let rel = path.trim_start_matches('/');
        if !valid_remote_path(rel) {
            return Err(TransportError::Failed("invalid path".into()));
        }
        let tmp = tempdir()?;
        let local = tmp.join("download");
        let script = format!(
            "get {} {}\n",
            join(&self.root, rel),
            sftp_quote(&local.to_string_lossy())?
        );
        let r = self.run(&script, self.connect_timeout * 3).await;
        let bytes = match r {
            Ok(_) => match tokio::fs::metadata(&local).await {
                Ok(m) if m.len() > max_bytes => {
                    Err(TransportError::Failed("file too large".into()))
                }
                Ok(_) => tokio::fs::read(&local)
                    .await
                    .map_err(|e| TransportError::Failed(e.to_string())),
                Err(_) => Err(TransportError::NotFound),
            },
            Err(e) => Err(e),
        };
        let _ = tokio::fs::remove_dir_all(&tmp).await;
        bytes
    }
    async fn probe(&self) -> TResult<()> {
        self.run(&format!("ls -1 {}\n", self.root), self.connect_timeout * 3)
            .await
            .map(|_| ())
    }
    fn describe(&self) -> String {
        format!(
            "sftp://{}@{}:{}{}",
            self.username, self.host, self.port, self.root
        )
    }
}

fn tempdir() -> TResult<PathBuf> {
    let p = std::env::temp_dir().join(format!("audeniq-xfer-{}", uuid::Uuid::new_v4().simple()));
    std::fs::create_dir_all(&p).map_err(|e| TransportError::Failed(e.to_string()))?;
    Ok(p)
}

